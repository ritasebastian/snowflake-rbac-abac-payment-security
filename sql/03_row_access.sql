-- Run as SYSADMIN, the owner of DATA and GOVERNANCE demo objects.
USE ROLE SYSADMIN;
-- Allow SYSADMIN to inspect all rows for setup and troubleshooting.
-- A privileged administrator is deliberately exempt in this demo.
CREATE OR REPLACE ROW ACCESS POLICY RBAC_ABAC_DEMO.GOVERNANCE.REGION_POLICY
AS (REGION_VALUE VARCHAR) RETURNS BOOLEAN ->
  IS_ROLE_IN_SESSION('SYSADMIN')
  OR IS_ROLE_IN_SESSION('DEMO_AUDITOR')
  OR IS_ROLE_IN_SESSION('DEMO_COMPLIANCE')
  OR EXISTS (
    SELECT 1 FROM RBAC_ABAC_DEMO.GOVERNANCE.REGION_ROLE_MAP m
    WHERE m.MARKET_REGION = REGION_VALUE
      AND IS_ROLE_IN_SESSION(m.ROLE_NAME)
  );

ALTER TABLE RBAC_ABAC_DEMO.DATA.PAYMENT_TRANSACTIONS
  ADD ROW ACCESS POLICY RBAC_ABAC_DEMO.GOVERNANCE.REGION_POLICY
  ON (MARKET_REGION);
