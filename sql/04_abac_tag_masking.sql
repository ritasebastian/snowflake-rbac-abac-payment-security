-- Run as SYSADMIN. Requires Enterprise Edition or higher for this demo.
USE ROLE SYSADMIN;
CREATE TAG IF NOT EXISTS RBAC_ABAC_DEMO.GOVERNANCE.DATA_CLASSIFICATION
  ALLOWED_VALUES 'PUBLIC', 'PII';

-- Mask is driven by BOTH column tag value (data attribute)
-- and the active entitlement role (subject attribute).
CREATE OR REPLACE MASKING POLICY RBAC_ABAC_DEMO.GOVERNANCE.STRING_CLASSIFICATION_MASK
AS (VAL VARCHAR) RETURNS VARCHAR ->
  CASE
    WHEN SYSTEM$GET_TAG_ON_CURRENT_COLUMN('RBAC_ABAC_DEMO.GOVERNANCE.DATA_CLASSIFICATION') = 'PII'
      AND NOT (
        IS_ROLE_IN_SESSION('DEMO_PII_READER')
        OR IS_ROLE_IN_SESSION('SYSADMIN')
      ) THEN '***MASKED***'
    ELSE VAL
  END;

ALTER TAG RBAC_ABAC_DEMO.GOVERNANCE.DATA_CLASSIFICATION
  SET MASKING POLICY RBAC_ABAC_DEMO.GOVERNANCE.STRING_CLASSIFICATION_MASK;

ALTER TABLE RBAC_ABAC_DEMO.DATA.PAYMENT_TRANSACTIONS
  MODIFY COLUMN CUSTOMER_EMAIL
  SET TAG RBAC_ABAC_DEMO.GOVERNANCE.DATA_CLASSIFICATION = 'PII';

-- Note: For column-specific tag-based masking, the tag must be applied to
-- the column (not merely created). Do not attach a second direct mask.
