-- Run AFTER assigning all four demo roles to your own Snowflake login.
-- In a production system, test with separate users and least-privilege grants.
-- Important: disable secondary roles to avoid accidentally inheriting more access.
USE SECONDARY ROLES NONE;

USE ROLE DEMO_US_ANALYST;
USE WAREHOUSE RBAC_ABAC_DEMO_WH;
SELECT CURRENT_ROLE() AS ROLE_NAME, COUNT(*) AS VISIBLE_ROWS
FROM RBAC_ABAC_DEMO.DATA.PAYMENT_TRANSACTIONS;
-- EXPECT: 3
SELECT TRANSACTION_ID, MARKET_REGION, CUSTOMER_EMAIL
FROM RBAC_ABAC_DEMO.DATA.PAYMENT_TRANSACTIONS ORDER BY TRANSACTION_ID;
-- EXPECT: US only, email ***MASKED***

USE ROLE DEMO_EU_ANALYST;
USE WAREHOUSE RBAC_ABAC_DEMO_WH;
SELECT CURRENT_ROLE() AS ROLE_NAME, COUNT(*) AS VISIBLE_ROWS
FROM RBAC_ABAC_DEMO.DATA.PAYMENT_TRANSACTIONS;
-- EXPECT: 3 (EU only)

USE ROLE DEMO_AUDITOR;
USE WAREHOUSE RBAC_ABAC_DEMO_WH;
SELECT CURRENT_ROLE() AS ROLE_NAME, COUNT(*) AS VISIBLE_ROWS
FROM RBAC_ABAC_DEMO.DATA.PAYMENT_TRANSACTIONS;
-- EXPECT: 8, emails masked

USE ROLE DEMO_COMPLIANCE;
USE WAREHOUSE RBAC_ABAC_DEMO_WH;
