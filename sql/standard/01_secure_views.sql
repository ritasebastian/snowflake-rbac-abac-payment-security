-- STANDARD EDITION FALLBACK (RBAC + secure-view approximation).
-- First execute 01_infrastructure.sql, but DO NOT execute 02, 03 or 04.
-- Requires SYSADMIN access and SECURITYADMIN to grant roles.
USE ROLE SYSADMIN;
USE WAREHOUSE RBAC_ABAC_DEMO_WH;
CREATE SCHEMA IF NOT EXISTS RBAC_ABAC_DEMO.REPORTING;

-- The base table is owned by SYSADMIN; analysts get ONLY view SELECT.
CREATE OR REPLACE SECURE VIEW RBAC_ABAC_DEMO.REPORTING.US_TRANSACTIONS AS
SELECT TRANSACTION_ID, CUSTOMER_ID, CUSTOMER_NAME,
       '***MASKED***'::VARCHAR AS CUSTOMER_EMAIL, MARKET_REGION,
       MERCHANT, AMOUNT_USD, STATUS, TRANSACTION_DATE
FROM RBAC_ABAC_DEMO.DATA.PAYMENT_TRANSACTIONS WHERE MARKET_REGION = 'US';

CREATE OR REPLACE SECURE VIEW RBAC_ABAC_DEMO.REPORTING.EU_TRANSACTIONS AS
SELECT TRANSACTION_ID, CUSTOMER_ID, CUSTOMER_NAME,
       '***MASKED***'::VARCHAR AS CUSTOMER_EMAIL, MARKET_REGION,
       MERCHANT, AMOUNT_USD, STATUS, TRANSACTION_DATE
FROM RBAC_ABAC_DEMO.DATA.PAYMENT_TRANSACTIONS WHERE MARKET_REGION = 'EU';

CREATE OR REPLACE SECURE VIEW RBAC_ABAC_DEMO.REPORTING.AUDIT_TRANSACTIONS AS
SELECT TRANSACTION_ID, CUSTOMER_ID, CUSTOMER_NAME,
       '***MASKED***'::VARCHAR AS CUSTOMER_EMAIL, MARKET_REGION,
       MERCHANT, AMOUNT_USD, STATUS, TRANSACTION_DATE
FROM RBAC_ABAC_DEMO.DATA.PAYMENT_TRANSACTIONS;

CREATE OR REPLACE SECURE VIEW RBAC_ABAC_DEMO.REPORTING.COMPLIANCE_TRANSACTIONS AS
SELECT * FROM RBAC_ABAC_DEMO.DATA.PAYMENT_TRANSACTIONS;
