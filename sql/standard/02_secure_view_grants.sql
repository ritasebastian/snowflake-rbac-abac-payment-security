USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS DEMO_STD_US_ANALYST;
CREATE ROLE IF NOT EXISTS DEMO_STD_EU_ANALYST;
CREATE ROLE IF NOT EXISTS DEMO_STD_AUDITOR;
CREATE ROLE IF NOT EXISTS DEMO_STD_COMPLIANCE;

GRANT ROLE DEMO_STD_US_ANALYST TO ROLE SYSADMIN;
GRANT ROLE DEMO_STD_EU_ANALYST TO ROLE SYSADMIN;
GRANT ROLE DEMO_STD_AUDITOR TO ROLE SYSADMIN;
GRANT ROLE DEMO_STD_COMPLIANCE TO ROLE SYSADMIN;

GRANT USAGE ON WAREHOUSE RBAC_ABAC_DEMO_WH TO ROLE DEMO_STD_US_ANALYST;
GRANT USAGE ON WAREHOUSE RBAC_ABAC_DEMO_WH TO ROLE DEMO_STD_EU_ANALYST;
GRANT USAGE ON WAREHOUSE RBAC_ABAC_DEMO_WH TO ROLE DEMO_STD_AUDITOR;
GRANT USAGE ON WAREHOUSE RBAC_ABAC_DEMO_WH TO ROLE DEMO_STD_COMPLIANCE;

GRANT USAGE ON DATABASE RBAC_ABAC_DEMO TO ROLE DEMO_STD_US_ANALYST;
GRANT USAGE ON DATABASE RBAC_ABAC_DEMO TO ROLE DEMO_STD_EU_ANALYST;
GRANT USAGE ON DATABASE RBAC_ABAC_DEMO TO ROLE DEMO_STD_AUDITOR;
GRANT USAGE ON DATABASE RBAC_ABAC_DEMO TO ROLE DEMO_STD_COMPLIANCE;

GRANT USAGE ON SCHEMA RBAC_ABAC_DEMO.REPORTING TO ROLE DEMO_STD_US_ANALYST;
GRANT USAGE ON SCHEMA RBAC_ABAC_DEMO.REPORTING TO ROLE DEMO_STD_EU_ANALYST;
GRANT USAGE ON SCHEMA RBAC_ABAC_DEMO.REPORTING TO ROLE DEMO_STD_AUDITOR;
GRANT USAGE ON SCHEMA RBAC_ABAC_DEMO.REPORTING TO ROLE DEMO_STD_COMPLIANCE;

GRANT SELECT ON VIEW RBAC_ABAC_DEMO.REPORTING.US_TRANSACTIONS TO ROLE DEMO_STD_US_ANALYST;
GRANT SELECT ON VIEW RBAC_ABAC_DEMO.REPORTING.EU_TRANSACTIONS TO ROLE DEMO_STD_EU_ANALYST;
GRANT SELECT ON VIEW RBAC_ABAC_DEMO.REPORTING.AUDIT_TRANSACTIONS TO ROLE DEMO_STD_AUDITOR;
GRANT SELECT ON VIEW RBAC_ABAC_DEMO.REPORTING.COMPLIANCE_TRANSACTIONS TO ROLE DEMO_STD_COMPLIANCE;

