-- Run first as an account administrator with SYSADMIN privileges.
-- Dedicated X-SMALL warehouse; avoids spending credits while idle.
USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS RBAC_ABAC_DEMO_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;
CREATE DATABASE IF NOT EXISTS RBAC_ABAC_DEMO;
CREATE SCHEMA IF NOT EXISTS RBAC_ABAC_DEMO.DATA;
CREATE SCHEMA IF NOT EXISTS RBAC_ABAC_DEMO.GOVERNANCE;
USE WAREHOUSE RBAC_ABAC_DEMO_WH;

CREATE OR REPLACE TABLE RBAC_ABAC_DEMO.DATA.PAYMENT_TRANSACTIONS (
    TRANSACTION_ID NUMBER(10,0),
    CUSTOMER_ID VARCHAR(20),
    CUSTOMER_NAME VARCHAR(100),
    CUSTOMER_EMAIL VARCHAR(200),
    MARKET_REGION VARCHAR(10),
    MERCHANT VARCHAR(100),
    AMOUNT_USD NUMBER(12,2),
    STATUS VARCHAR(20),
    TRANSACTION_DATE DATE
);
